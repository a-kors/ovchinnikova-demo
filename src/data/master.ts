// неразрывный пробел после коротких слов, чтобы они не висели в конце строки
const SHORT = /(^|[\s(«])(в|во|и|с|со|к|ко|о|об|у|а|я|на|не|ни|по|за|до|из|от|же|но|что|как|для|при|без)\s+/gi;
const nb = (t: string) => t.replace(SHORT, (_m, p, w) => `${p}${w}\u00a0`).replace(SHORT, (_m, p, w) => `${p}${w}\u00a0`);
function nbDeep<T>(v: T): T {
  if (typeof v === 'string') return nb(v) as T;
  if (Array.isArray(v)) return v.map(nbDeep) as T;
  if (v && typeof v === 'object') {
    const o: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v)) o[k] = k === 'kind' || k === 'n' || k === 'years' ? x : nbDeep(x);
    return o as T;
  }
  return v;
}

